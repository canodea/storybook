// Generates src/styles/colors.css and src/foundations/colors.data.ts from design-ref/colors.txt.
// Usage: node scripts/gen-colors.mjs [path/to/colors.txt]
import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = resolve(root, process.argv[2] ?? '../design-ref/colors.txt');

const idByCollection = (name) =>
  name.includes('Temel') ? 'primitive' : name.includes('Anlamsal') ? 'semantic' : 'product';

function parseValue(raw) {
  const text = raw.trim();
  const opacity = text.match(/\s@(\d+)%\s*$/);
  const core = opacity ? text.slice(0, opacity.index).trim() : text;
  const [hex, alias] = core.split('>').map((part) => part.trim());
  return { hex, alias: alias || undefined, opacity: opacity ? Number(opacity[1]) : undefined };
}

const collections = [];
for (const line of readFileSync(inputPath, 'utf8').split('\n')) {
  if (!line.trim() || line.startsWith('#')) {
    if (line.startsWith('##')) {
      const [name, modes] = line.slice(2).split('|');
      collections.push({ id: idByCollection(name), name: name.trim(), modes: modes.split(','), tokens: [] });
    }
    continue;
  }
  const [name, ...cells] = line.split('|');
  const collection = collections.at(-1);
  const values = cells.slice(0, collection.modes.length);
  const token = {
    name: name.trim(),
    cssVar: `--odea-${name.trim().replaceAll('/', '-')}`,
    group: name.trim().split('/')[0],
    light: parseValue(values[0]),
    dark: values[1] ? parseValue(values[1]) : undefined,
    description: cells.slice(collection.modes.length).join('|').trim() || undefined,
  };
  collection.tokens.push(token);
}

assert.equal(collections.length, 3, 'expected three collections');
const byName = new Map(collections.flatMap((c) => c.tokens.map((t) => [t.name, t])));
assert.equal(byName.size, collections.reduce((sum, c) => sum + c.tokens.length, 0), 'duplicate token names');

for (const token of byName.values()) {
  for (const mode of [token.light, token.dark]) {
    if (mode?.alias) assert.ok(byName.has(mode.alias), `unknown alias ${mode.alias} on ${token.name}`);
  }
}

const cssValue = (value) =>
  value.alias && value.opacity === undefined ? `var(${byName.get(value.alias).cssVar})` : value.hex;
const rule = (token, mode) => `  ${token.cssVar}: ${cssValue(token[mode])};`;

const blocks = [];
for (const collection of collections) {
  const primitives = collection.id === 'primitive';
  const light = collection.tokens.map((t) => rule(t, 'light'));
  blocks.push(`/* ${collection.name} */\n:root {\n${light.join('\n')}\n}`);
  if (!primitives) {
    const dark = collection.tokens.filter((t) => t.dark).map((t) => rule(t, 'dark'));
    if (dark.length) blocks.push(`/* ${collection.name} — Dark */\n[data-theme="dark"] {\n${dark.join('\n')}\n}`);
  }
}

const css = `/* Generated by scripts/gen-colors.mjs from design-ref/colors.txt. Do not edit by hand. */\n\n${blocks.join('\n\n')}\n`;
mkdirSync(resolve(root, 'src/styles'), { recursive: true });
writeFileSync(resolve(root, 'src/styles/colors.css'), css);

const data = collections.map((collection) => ({
  id: collection.id,
  name: collection.name,
  modes: collection.modes,
  tokens: collection.tokens.map((token) => ({
    name: token.name,
    cssVar: token.cssVar,
    group: token.group,
    light: token.light.hex,
    ...(token.dark ? { dark: token.dark.hex } : {}),
    ...(token.light.alias ? { lightAlias: token.light.alias } : {}),
    ...(token.dark?.alias ? { darkAlias: token.dark.alias } : {}),
    ...(token.description ? { description: token.description } : {}),
  })),
}));

const ts = `/* Generated by scripts/gen-colors.mjs from design-ref/colors.txt. Do not edit by hand. */

export type ColorCollectionId = 'primitive' | 'semantic' | 'product';

export type ColorToken = {
  /** Figma token path, e.g. text/primary */
  name: string;
  /** CSS custom property, e.g. --odea-text-primary */
  cssVar: string;
  /** First path segment, e.g. text */
  group: string;
  light: string;
  dark?: string;
  lightAlias?: string;
  darkAlias?: string;
  description?: string;
};

export type ColorCollection = {
  id: ColorCollectionId;
  name: string;
  modes: string[];
  tokens: ColorToken[];
};

export const colorCollections: ColorCollection[] = ${JSON.stringify(data, null, 2)};

export const primitiveCollection = colorCollections.find((c) => c.id === 'primitive')!;
export const semanticCollection = colorCollections.find((c) => c.id === 'semantic')!;
export const productCollection = colorCollections.find((c) => c.id === 'product')!;
`;
mkdirSync(resolve(root, 'src/foundations'), { recursive: true });
writeFileSync(resolve(root, 'src/foundations/colors.data.ts'), ts);

const total = collections.reduce((sum, c) => sum + c.tokens.length, 0);
console.log(
  `colors: ${collections.map((c) => `${c.tokens.length} ${c.id}`).join(', ')} (${total} tokens) -> src/styles/colors.css, src/foundations/colors.data.ts`,
);
